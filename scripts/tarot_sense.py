def sense_of(card: Dict) -> str:
    """这张牌的那一秒身体感（正逆共用同一条，氛围交给低语去分）。"""
    if card.get("arcana") == "major":
        return (MAJOR.get(int(card["id"])) or {}).get("sense", "")
    suit = card.get("suit") or ""
    rank = card.get("rank") or ""
    pool = SUIT_SENSE.get(suit) or []
    if not pool:
        return ""
    idx = _MINOR_RANKS.index(rank) if rank in _MINOR_RANKS else 0
    return pool[idx % len(pool)]


def whisper_of(card: Dict, orientation: str) -> str:
    """正/逆位的低语：从 deck 的寄语退化到本层的细腻句。"""
    key = "up" if orientation != "rev" else "rev"
    if card.get("arcana") == "major":
        entry = MAJOR.get(int(card["id"])) or {}
        return entry.get(key, "")
    info = RANK_WHISPER.get(card.get("rank") or "", {})
    return info.get(key, "")


def lines_for(card: Dict, orientation: str) -> List[str]:
    """解读正文：一句身体感 + 一句低语。没有文案时优雅退化为空列表。"""
    out: List[str] = []
    sense = sense_of(card)
    if sense:
        out.append(sense)
    whisper = whisper_of(card, orientation)
    if whisper:
        out.append(whisper)
    return out


def all_cards_covered(cards: Optional[List[Dict]] = None) -> List[int]:
    """自检用：返回缺少文案的牌 id（空列表即全部覆盖）。"""
    import tarot_deck
    missing: List[int] = []
    for c in (cards or tarot_deck.ALL_CARDS):
        if not sense_of(c):
            missing.append(int(c["id"]))
        if not whisper_of(c, "up") or not whisper_of(c, "rev"):
            missing.append(int(c["id"]))
    return sorted(set(missing))
